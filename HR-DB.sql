    EMP_ID VARCHAR(20),
    F_NAME VARCHAR(50),
    L_NAME VARCHAR(50),
    SSN VARCHAR(20),
    B_DATE VARCHAR(30),
    SEX VARCHAR(10),
    ADDRESS VARCHAR(500),
    JOB_ID VARCHAR(20),
    SALARY VARCHAR(20),
    MANAGER_ID VARCHAR(20),
    DEP_ID VARCHAR(20)
);

BULK INSERT #TempEmployees
FROM 'C:\Users\Mahmoud\Downloads\HR-Database\Employees.txt'
WITH (
    FIRSTROW = 1,
    FIELDTERMINATOR = ',',
    ROWTERMINATOR = '\n',
    TABLOCK
);

INSERT INTO EMPLOYEES (EMP_ID, F_NAME, L_NAME, SSN, B_DATE, SEX, ADDRESS, JOB_ID, SALARY, MANAGER_ID, DEP_ID)
SELECT 
    LEFT(EMP_ID, 5) AS EMP_ID,
    LEFT(F_NAME, 15) AS F_NAME,
    LEFT(L_NAME, 15) AS L_NAME,
    LEFT(SSN, 6) AS SSN,
    CASE 
        WHEN ISDATE(B_DATE) = 1 THEN TRY_CONVERT(DATE, B_DATE, 101)
        ELSE NULL
    END AS B_DATE,
    LEFT(SEX, 1) AS SEX,
    LEFT(ADDRESS, 100) AS ADDRESS,
    LEFT(JOB_ID, 3) AS JOB_ID,
    TRY_CAST(SALARY AS DECIMAL(10,2)) AS SALARY,
    CASE WHEN MANAGER_ID != '' THEN LEFT(MANAGER_ID, 5) ELSE NULL END AS MANAGER_ID,
    LEFT(DEP_ID, 1) AS DEP_ID
FROM #TempEmployees
WHERE EMP_ID IS NOT NULL AND EMP_ID != '';

DROP TABLE #TempEmployees;
GO

